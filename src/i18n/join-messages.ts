export type JoinMessageKey = keyof (typeof joinMessages)["en"];

export function getJoinTranslations(language: JoinLanguage) {
  return (
    key: JoinMessageKey,
    variables: Record<string, string | number> = {},
  ): string => {
    const template: string = joinMessages[language][key];
    return (
    Object.entries(variables).reduce(
      (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
      template,
    ));
  };
}

export function joinStatusKey(status: JoinInvitationStatus): JoinMessageKey {
  const keys: Record<JoinInvitationStatus, JoinMessageKey> = {
    VALID: "join.status.invalid",
    EXPIRED: "join.status.expired",
    REVOKED: "join.status.revoked",
    USED: "join.status.used",
    INVALID: "join.status.invalid",
    ALREADY_MEMBER: "join.status.alreadyMember",
    WORKSPACE_UNAVAILABLE: "join.status.unavailable",
    PERSONAL_WORKSPACE_NOT_JOINABLE: "join.status.personalNotJoinable",
  };

  return keys[status];
}
