export type ReportMessageKey = keyof (typeof reportMessages)["en"];
export type ReportLabels = Readonly<Record<ReportMessageKey, string>>;

const languageCatalogs: Readonly<Record<ReportMessageLanguage, ReportLabels>> = reportMessages;

export function getReportLabels(language: string | null | undefined): ReportLabels {
  return languageCatalogs[language === "fr" || language === "de" ? language : "en"];
}

export function formatReportLabel(
  labels: ReportLabels,
  key: ReportMessageKey,
  variables: Record<string, string | number> = {},
): string {
  return Object.entries(variables).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    labels[key],
  );
}
