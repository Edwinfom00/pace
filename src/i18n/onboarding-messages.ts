export type OnboardingMessageKey = keyof (typeof onboardingMessages)["en"];

export function getOnboardingTranslations(language: OnboardingLanguage) {
  const dictionary = onboardingMessages[language];
  return (key: OnboardingMessageKey, variables: Record<string, string | number> = {}): string =>
    Object.entries(variables).reduce<string>(
      (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
      String(dictionary[key]),
    );
}
