export type AssistantLanguage = keyof typeof assistantMessages;
export type AssistantMessageKey = keyof (typeof assistantMessages)["en"];
export type AssistantMessages = Readonly<Record<AssistantMessageKey, string>>;

export function getAssistantMessages(
  language: string | null | undefined,
): AssistantMessages {
  return assistantMessages[
    language === "fr" || language === "de" ? language : "en"
  ];
}

export function formatAssistantMessage(
  messages: AssistantMessages,
  key: AssistantMessageKey,
  variables: Record<string, string | number> = {},
): string {
  return Object.entries(variables).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[key],
  );
}
